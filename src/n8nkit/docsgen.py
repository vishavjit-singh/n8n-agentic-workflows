def _md_escape(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def _flags(n) -> str:
    out = []
    if n.raw.get("retryOnFail"):
        out.append(f"retry {n.raw.get('maxTries', 3)}× / {n.raw.get('waitBetweenTries', 1000)} ms")
    if n.raw.get("alwaysOutputData"):
        out.append("always output data")
    if n.raw.get("onError"):
        out.append(f"onError: {n.raw['onError']}")
    return ", ".join(out)


def _side_effects(wf: Workflow) -> list[str]:
    out = []
    for n in wf.nodes:
        p = n.params
        if n.type.endswith(".googleSheets"):
            sheet = (p.get("sheetName") or {}).get("value", "")
            out.append(f"**{n.name}**: Google Sheets `{p.get('operation')}` on tab `{sheet}`")
        elif n.type.endswith(".gmail"):
            out.append(f"**{n.name}**: Gmail {'draft (not sent)' if p.get('resource') == 'draft' else 'send'}")
        elif n.type.endswith(".slack"):
            out.append(f"**{n.name}**: Slack message to `{(p.get('channelId') or {}).get('value', '')}`")
        elif n.type.endswith(".googleCalendar"):
            op = "availability check" if p.get("operation") == "availability" else "event create"
            out.append(f"**{n.name}**: Google Calendar {op}")
        elif n.type.endswith(".respondToWebhook"):
            code = (p.get("options") or {}).get("responseCode", 200)
            out.append(f"**{n.name}**: HTTP {code} response to the caller")
    return out


def _trigger_section(wf: Workflow) -> list[str]:
    lines = []
    for t in wf.triggers():
        p = t.params
        if t.type.endswith(".webhook"):
            mode = p.get("responseMode", "onReceived")
            how = ("answers from a Respond to Webhook node" if mode == "responseNode"
                   else f"answers {(p.get('options') or {}).get('responseCode', 200)} immediately, then runs")
            lines.append(f"- **{t.name}**: `{p.get('httpMethod', 'GET')} /webhook/{p.get('path')}` ({how}). "
                         f"Test URL while editing: `/webhook-test/{p.get('path')}`.")
        elif t.type.endswith(".scheduleTrigger"):
            iv = ((p.get("rule") or {}).get("interval") or [{}])[0]
            lines.append(f"- **{t.name}**: schedule, cron `{iv.get('expression', '')}` in the instance timezone "
                         "(`GENERIC_TIMEZONE`).")
        elif t.type.endswith(".errorTrigger"):
            lines.append(f"- **{t.name}**: starts when a workflow whose `settings.errorWorkflow` is "
                         f"`{wf.id}` fails.")
    return lines


def render_doc(wf: Workflow, all_wfs: list[Workflow], sample: tuple[dict, Execution] | None = None) -> str:
    about = wf.notes()[0] if wf.notes() else ""
    about = re.sub(r"^## .*\n", "", about).strip()
    nodes = [n for n in wf.nodes if not n.is_note]
    creds: dict[tuple[str, str], list[str]] = defaultdict(list)
    for n in nodes:
        for ctype, ref in n.credentials.items():
            creds[(ctype, ref.get("name", ""))].append(n.name)
    env = sorted({m for n in nodes for _p, s in walk_strings(n.params) for m in ENV.findall(s)})
    urls = [(n.name, n.params.get("url")) for n in nodes if n.params.get("url")]
    users = [o for o in all_wfs if o.settings.get("errorWorkflow") == wf.id]

    out = [f"# {wf.name}", "",
           f"> Generated by `n8nkit docs` from [`workflows/{wf.slug}.json`](../../workflows/{wf.slug}.json). "
           "Edit the workflow, then run `make docs`.", "",
           f"![{wf.name}](../images/workflows/{wf.slug}.png)", "", about, "",
           "| | |", "|---|---|", f"| Workflow ID | `{wf.id}` |", f"| Nodes | {len(nodes)} |",
           f"| Error workflow | `{wf.settings.get('errorWorkflow', '—')}` |",
           f"| Execution order | `{wf.settings.get('executionOrder')}` |", "",
           "## Trigger", ""] + _trigger_section(wf) + [""]
    if users:
        out += ["Used as the error workflow by: " + ", ".join(f"[{o.name}]({o.slug}.md)" for o in users) + ".", ""]
    out += ["## Nodes", "", "| # | Node | Type | Kind | Credential | Resilience |", "|---|---|---|---|---|---|"]
    for i, n in enumerate(nodes, 1):
        cred = ", ".join(f"`{r.get('name')}`" for r in n.credentials.values())
        out.append(f"| {i} | {_md_escape(n.name)} | `{n.type.split('.')[-1]}` v{n.type_version} | {n.kind} | "
                   f"{cred} | {_flags(n)} |")
    out += ["", "## Credentials to create", ""]
    if creds:
        out += ["Create these in n8n (**Credentials → Add credential**) with the same names, or pick your own in "
                "each node after import.", "", "| Credential type | Name used in the template | Used by | Notes |",
                "|---|---|---|---|"]
        for (ctype, name), users_ in sorted(creds.items()):
            out.append(f"| `{ctype}` | {name} | {', '.join(users_)} | {CRED_HELP.get(ctype, '')} |")
    else:
        out.append("None.")
    out += ["", "## Environment variables", ""]
    out += [f"- `{e}`: {ENV_HELP.get(e, '')}" for e in env] or ["None."]
    if urls:
        out += ["", "## HTTP endpoints called", ""] + [f"- **{n}**: `{u}`" for n, u in urls]
    out += ["", "## What it writes or sends", ""] + [f"- {s}" for s in _side_effects(wf)]
    ai = [n for n in nodes if n.spec and n.spec.accepts]
    if ai:
        out += ["", "## AI nodes", ""]
        for n in ai:
            subs = {ct: [s.name for s in wf.sub_nodes(n.name, ct)] for ct in catalog.AI_CONNECTION_TYPES}
            parts = [f"{ct.replace('ai_', '')}: {', '.join(v)}" for ct, v in subs.items() if v]
            out.append(f"- **{n.name}** ({n.spec.label}): {'; '.join(parts)}")
            for parser in subs["ai_outputParser"]:
                schema = json.loads(wf.by_name[parser].params.get("inputSchema", "{}"))
                fields = ", ".join(f"`{k}`" for k in schema.get("properties", {}))
                out.append(f"  - output schema `{schema.get('title', '')}`: {fields}")
    if sample:
        payload, exe = sample
        hook = next((t for t in wf.triggers() if t.type.endswith(".webhook")), None)
        out += ["", "## Try it", ""]
        if hook:
            out += ["```bash", f"curl -s -X POST http://localhost:5678/webhook/{hook.params.get('path')} \\",
                    "  -H 'content-type: application/json' \\", f"  -d '{json.dumps(payload)}'", "```", ""]
        out += ["Simulated run of that input (`n8nkit simulate`, fake services, SYNTHETIC data):", "", "```",
                exe.trace_text(), "```"]
    out += ["", "## Setup", "",
            "1. Import the file: **Workflows → Import from File**, or `n8n import:workflow "
            f"--input=workflows/{wf.slug}.json`.",
            "2. Create the credentials above and select them in each node that shows a warning.",
            "3. Set the environment variables (see `.env.example`), or replace the `$env` expressions with values.",
            "4. Import `00-error-handler.json` too: the error workflow is linked by ID." if wf.settings.get(
                "errorWorkflow") else "4. Keep this workflow's ID so the other templates can reference it.",
            "5. Run it once with **Test workflow** and the test URL, then activate it.", ""]
    return "\n".join(out)


def write_docs(workflows: list[Workflow], out_dir: Path, samples: dict[str, tuple[dict, Execution]]) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for wf in workflows:
        p = out_dir / f"{wf.slug}.md"
        p.write_text(render_doc(wf, workflows, samples.get(wf.slug)))
        paths.append(p)
    return paths
